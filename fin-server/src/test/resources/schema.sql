-- The tables from database/FinanceDB.sql in syntax H2 understands, for tests only.
CREATE SCHEMA IF NOT EXISTS finance;

CREATE TABLE IF NOT EXISTS finance.account (
    account_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(32) UNIQUE NOT NULL,
    cash         NUMERIC(12, 4),
    created_date DATE DEFAULT CURRENT_DATE
);

CREATE TABLE IF NOT EXISTS finance.investment (
    investment_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticker        VARCHAR(32) UNIQUE NOT NULL,
    category      VARCHAR(64),
    color         VARCHAR(16),
    price         NUMERIC(12, 4),
    sequence      INT,
    created_date  DATE DEFAULT CURRENT_DATE
);

CREATE TABLE IF NOT EXISTS finance.position (
    position_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id    INT,
    investment_id INT,
    shares        NUMERIC(12, 4),
    created_date  DATE DEFAULT CURRENT_DATE,
    CONSTRAINT fk_position_account FOREIGN KEY (account_id) REFERENCES finance.account (account_id),
    CONSTRAINT fk_position_investment FOREIGN KEY (investment_id) REFERENCES finance.investment (investment_id),
    CONSTRAINT uq_position_account_investment UNIQUE (account_id, investment_id)
);

CREATE TABLE IF NOT EXISTS finance.hsa (
    hsa_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    balance      NUMERIC(12, 4),
    created_date DATE DEFAULT CURRENT_DATE
);
